#!/usr/bin/env bash
# Renders db/include/cms/db/tables.hpp from a live database.
#
# The header is the one place C++ learns the schema's table, column and type names, so a hand-written
# copy drifts the first time a migration lands. This script is the only producer of that file: it
# reads information_schema.columns for schema public and prints one sqlpp23 table struct per table.
#
# Usage: tools/render-tables.sh [path]
#   with no path the header goes to stdout.
#
# Connection comes from the usual libpq environment: PGHOST, PGPORT, PGDATABASE, PGUSER, PGPASSWORD.
# tools/check-db.sh starts a scratch cluster from deploy/plan, renders into a temporary file and
# compares, so the committed header is provably what this script prints.
#
# SQL type to C++ type, the one mapping that is a choice rather than a copy:
#   uuid, inet, jsonb, text, USER-DEFINED (enum)           -> ::sqlpp::text
#   timestamp with time zone, timestamp without time zone  -> ::sqlpp::timestamp
#   date                                                   -> ::sqlpp::date
#   time                                                   -> ::sqlpp::time
#   bigint, integer, smallint                              -> ::sqlpp::integral
#   boolean                                                -> ::sqlpp::boolean
#   bytea                                                  -> ::sqlpp::blob
# Any other SQL type aborts the render instead of guessing. A nullable column becomes
# std::optional<...>. has_default marks a column an insert may omit: the server supplies it through a
# DEFAULT, an identity or generated expression, or by storing NULL. _required_insert_columns is the
# rest, the columns that are NOT NULL and have no server-side default.
#
# The output is byte-identical across runs: tables are sorted by name, columns follow
# ordinal_position, and no timestamp, host name or absolute path is written.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${1:-}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

die() { printf 'render-tables: %s\n' "$*" >&2; exit 1; }

command -v psql >/dev/null 2>&1 || die "psql is required"

query="
SELECT c.table_name, c.column_name, c.data_type, c.is_nullable,
       CASE WHEN c.column_default IS NOT NULL
                 OR c.is_identity = 'YES'
                 OR c.is_generated = 'ALWAYS'
                 OR c.is_nullable = 'YES'
            THEN 'default' ELSE 'required' END
FROM information_schema.columns AS c
JOIN information_schema.tables AS t
  ON t.table_schema = c.table_schema AND t.table_name = c.table_name
WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
"

psql -X -q -t -A -F '|' -v ON_ERROR_STOP=1 -c "$query" > "$work/columns.txt" \
  || die "the schema could not be read; set PGHOST, PGPORT, PGDATABASE and PGUSER"

awk '
function upper_first(word) {
  return toupper(substr(word, 1, 1)) substr(word, 2)
}

function pascal(word,   parts, count, i, result) {
  count = split(word, parts, "_")
  result = ""
  for (i = 1; i <= count; i++) {
    result = result upper_first(parts[i])
  }
  return result
}

function camel(word,   parts, count, i, result) {
  count = split(word, parts, "_")
  result = tolower(parts[1])
  for (i = 2; i <= count; i++) {
    result = result upper_first(parts[i])
  }
  return result
}

function sqlpp_type(sql_type) {
  if (sql_type == "uuid" || sql_type == "inet" || sql_type == "jsonb" ||
      sql_type == "text" || sql_type == "USER-DEFINED") {
    return "::sqlpp::text"
  }
  if (sql_type == "timestamp with time zone" || sql_type == "timestamp without time zone") {
    return "::sqlpp::timestamp"
  }
  if (sql_type == "date") { return "::sqlpp::date" }
  if (sql_type == "time") { return "::sqlpp::time" }
  if (sql_type == "bigint" || sql_type == "integer" || sql_type == "smallint") {
    return "::sqlpp::integral"
  }
  if (sql_type == "boolean") { return "::sqlpp::boolean" }
  if (sql_type == "bytea") { return "::sqlpp::blob" }
  return ""
}

function close_table() {
  if (table == "") { return }
  if (required == "") {
    required_set = "sqlpp::detail::type_set<>"
  } else {
    required_set = "sqlpp::detail::type_set<" required ">"
  }
  printf "  SQLPP_CREATE_NAME_TAG_FOR_SQL_AND_CPP(%s, %s);\n", table, camel(table)
  printf "  template <typename T>\n"
  printf "  using _table_columns =\n"
  printf "      sqlpp::table_columns<T, %s>;\n", columns
  printf "  using _required_insert_columns = %s;\n", required_set
  printf "};\n"
  count++
  types[count] = pascal(table)
  variables[count] = camel(table)
  table = ""
}

BEGIN {
  FS = "|"
  count = 0
  total = 0
  table = ""
  print "#pragma once"
  print ""
  print "// Generated by tools/render-tables.sh from the applied schema. Edit the generator, not this"
  print "// file. Tables are sorted and columns follow ordinal_position, and nothing here depends on"
  print "// the clock, the host or the working directory, so two runs against one schema agree."
  print ""
  print "#include <optional>"
  print ""
  print "#include <sqlpp23/sqlpp23.h>"
  print ""
  print "namespace cms::db {"
  print ""
}

NF < 5 { next }

$1 != table {
  if (table != "") { close_table(); printf "\n" }
  table = $1
  columns = ""
  required = ""
  printf "struct %s_ {\n", pascal(table)
}

{
  type = sqlpp_type($3)
  if (type == "") {
    printf "render-tables: no C++ type for %s on %s.%s\n", $3, table, $2 > "/dev/stderr"
    exit 1
  }
  name = pascal($2)
  if ($4 == "YES") { type = "std::optional<" type ">" }
  printf "  struct %s {\n", name
  printf "    SQLPP_CREATE_NAME_TAG_FOR_SQL_AND_CPP(%s, %s);\n", $2, camel($2)
  printf "    using data_type = %s;\n", type
  if ($5 == "default") {
    printf "    using has_default = std::true_type;\n"
  } else {
    printf "    using has_default = std::false_type;\n"
    required = required (required == "" ? "" : ", ") name
  }
  printf "  };\n"
  columns = columns (columns == "" ? "" : ", ") name
  total++
}

END {
  close_table()
  printf "\n"
  for (i = 1; i <= count; i++) {
    printf "using %s = ::sqlpp::table_t<%s_>;\n", types[i], types[i]
  }
  printf "\n"
  for (i = 1; i <= count; i++) {
    printf "inline const %s %s{};\n", types[i], variables[i]
  }
  printf "\n}  // namespace cms::db\n"
  printf "render-tables: %d table(s), %d column(s)\n", count, total > "/dev/stderr"
}
' "$work/columns.txt" > "$work/tables.hpp" || die "the schema could not be rendered"

if [ -n "$out" ]; then
  [ -d "$(dirname "$out")" ] || die "no directory for $out"
  cp "$work/tables.hpp" "$out"
else
  cat "$work/tables.hpp"
fi

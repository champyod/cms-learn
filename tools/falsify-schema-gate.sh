#!/usr/bin/env bash
# Proves the schema gate and the apply wrapper can fail.
#
# The apply wrapper is the only thing standing between a hand-edited plan and a database, and the gate
# is the only thing that notices when the plan drifts from its source. Each case below breaks one of
# those in a throwaway copy and requires the specific message, not merely a non-zero exit: a harness
# that crashes looks like it worked.
#
# Usage: bash tools/falsify-schema-gate.sh
set -uo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

pass=0
fail=0

stage() {
  local dir="$1"
  rm -rf "$dir"
  mkdir -p "$dir/tools"
  cp -a "$repo/deploy" "$dir/"
  cp -a "$repo/tools/check-schema.sh" "$repo/tools/apply-plan.sh" "$repo/tools/compare-plan.ts" "$dir/tools/"
}

# case_of <name> <expected substring> <command> <mutation run inside the staged root>
case_of() {
  local name="$1" expect="$2" command="$3" mutate="$4"
  local dir="$work/$name" before after out rc
  stage "$dir"
  before="$(cd "$dir" && find deploy -type f -exec sha256sum {} + | sort | sha256sum)"
  ( cd "$dir" && eval "$mutate" ) || { printf 'SETUP FAILED  %s\n' "$name"; fail=$((fail + 1)); return; }
  after="$(cd "$dir" && find deploy -type f -exec sha256sum {} + | sort | sha256sum)"
  if [ "$before" = "$after" ]; then
    printf 'SETUP FAILED  %s — mutation changed nothing (stale pattern?)\n' "$name"
    fail=$((fail + 1))
    return
  fi
  out="$( cd "$dir" && eval "$command" 2>&1 )"
  rc=$?
  if [ "$rc" -eq 0 ]; then
    printf 'NOT CAUGHT    %s — the check passed a broken plan\n' "$name"
    fail=$((fail + 1))
  elif [[ "$out" != *"$expect"* ]]; then
    printf 'WRONG MESSAGE %s — expected "%s", got:\n%s\n' "$name" "$expect" "$out"
    fail=$((fail + 1))
  else
    printf 'caught        %s\n' "$name"
    pass=$((pass + 1))
  fi
}

# Control: an untouched copy must pass, or every case below is meaningless.
control="$work/control"
stage "$control"
if ( cd "$control" && bash tools/check-schema.sh >/dev/null 2>&1 ); then
  printf 'behaved       control (an unmodified tree passes)\n'
  pass=$((pass + 1))
else
  printf 'BROKEN        control — the gate rejects a valid tree\n'
  fail=$((fail + 1))
fi

case_of "plan-sql-edited" "does not match deploy/plan/CHECKSUMS" \
  "bash tools/apply-plan.sh" \
  "printf '\n-- edited by hand\n' >> deploy/plan/0001_init.sql"

case_of "plan-json-edited" "does not match deploy/plan/CHECKSUMS" \
  "bash tools/apply-plan.sh" \
  "sed -i 's/\"operation\": \"create\"/\"operation\": \"update\"/' deploy/plan/0001_init.json"

case_of "checksums-removed" "deploy/plan/CHECKSUMS is missing" \
  "bash tools/apply-plan.sh" \
  "rm deploy/plan/CHECKSUMS"

case_of "plan-file-removed" "deploy/plan/0001_init.sql is missing" \
  "bash tools/check-schema.sh" \
  "rm deploy/plan/0001_init.sql"

case_of "source-moved-ahead" "is not what deploy/schema/main.sql renders" \
  "bash tools/check-schema.sh" \
  "printf 'CREATE TABLE gate_probe (id integer);\n' > deploy/schema/gate_probe.sql && printf '\\\\i gate_probe.sql\n' >> deploy/schema/main.sql"

# A plan and its digests can both be regenerated by hand. Only a fresh render catches that, which is
# why the gate does not rely on the checksums alone.
case_of "plan-and-digests-forged" "is not what deploy/schema/main.sql renders" \
  "bash tools/check-schema.sh" \
  "printf '\n-- forged\n' >> deploy/plan/0001_init.sql && ( cd . && sha256sum deploy/plan/0001_init.sql deploy/plan/0001_init.json > deploy/plan/CHECKSUMS )"

printf '\n%s case(s) behaved, %s did not\n' "$pass" "$fail"
[ "$fail" -eq 0 ]

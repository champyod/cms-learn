import type { Gate, GateCommand } from "../contract.ts";

const APPLY_PLAN: GateCommand = { command: "bash", args: ["tools/apply-plan.sh"] };

export const SCHEMA_GATE: Gate = {
  id: "schema",
  stage: ["deploy", "tools/check-schema.sh", "tools/apply-plan.sh", "tools/compare-plan.ts"],
  command: { command: "bash", args: ["tools/check-schema.sh"] },
  cases: [
    {
      name: "control",
      expect: { status: "zero" },
    },
    {
      name: "plan-sql-edited",
      plant: [{ kind: "append", path: "deploy/plan/0001_init.sql", content: "\n-- edited by hand\n" }],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "does not match deploy/plan/CHECKSUMS" },
    },
    {
      name: "plan-json-edited",
      plant: [
        {
          kind: "replaceAll",
          path: "deploy/plan/0001_init.json",
          find: "\"operation\": \"create\"",
          replace: "\"operation\": \"update\"",
          matches: 99,
        },
      ],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "does not match deploy/plan/CHECKSUMS" },
    },
    {
      name: "checksums-removed",
      plant: [{ kind: "remove", path: "deploy/plan/CHECKSUMS" }],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "deploy/plan/CHECKSUMS is missing" },
    },
    {
      name: "plan-file-removed",
      plant: [{ kind: "remove", path: "deploy/plan/0001_init.sql" }],
      expect: { status: "non-zero", message: "deploy/plan/0001_init.sql is missing" },
    },
    {
      name: "source-moved-ahead",
      plant: [
        { kind: "write", path: "deploy/schema/gate_probe.sql", content: "CREATE TABLE gate_probe (id integer);\n" },
        { kind: "append", path: "deploy/schema/main.sql", content: "\\i gate_probe.sql\n" },
      ],
      expect: { status: "non-zero", message: "is not what deploy/schema/main.sql renders" },
    },
    {
      name: "plan-and-digests-forged",
      // A plan and its digests can both be regenerated by hand; only a fresh render catches the drift.
      plant: [
        {
          kind: "run",
          script: "printf '\\n-- forged\\n' >> deploy/plan/0001_init.sql && sha256sum deploy/plan/0001_init.sql deploy/plan/0001_init.json > deploy/plan/CHECKSUMS",
          verify: "sha256sum --quiet --check deploy/plan/CHECKSUMS && grep -q -- '-- forged' deploy/plan/0001_init.sql",
        },
      ],
      expect: { status: "non-zero", message: "is not what deploy/schema/main.sql renders" },
    },
  ],
};

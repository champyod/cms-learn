import type { Gate, GateCommand } from "../contract.ts";

const APPLY_PLAN: GateCommand = { command: "bash", args: ["tools/apply-plan.sh"] };

export const SCHEMA_GATE: Gate = {
  id: "schema",
  stage: [
    "deploy",
    "docs/dependencies.md",
    "tools/pinned-pgschema.sh",
    "tools/check-schema.sh",
    "tools/apply-plan.sh",
    "tools/compare-plan.ts",
  ],
  command: { command: "bash", args: ["tools/check-schema.sh"] },
  cases: [
    {
      name: "control",
      expect: { status: "zero" },
    },
    {
      // The host upgrade this gate was written for: a binary of another version is the only one named, and
      // the gate must refuse before it renders or applies anything rather than report the difference as
      // drift in the plan.
      name: "schema-tool-version-mismatch",
      plant: [
        { kind: "write", path: "fakebin/pgschema", content: "#!/usr/bin/env bash\nprintf '9.9.9\\n'\n" },
        { kind: "run", script: "chmod +x fakebin/pgschema", verify: "test -x fakebin/pgschema" },
      ],
      command: {
        command: "bash",
        args: ["tools/apply-plan.sh"],
        env: {
          CMSLEARN_PGSCHEMA: "{root}/fakebin/pgschema",
          HOME: "{root}/nohome",
        },
      },
      expect: { status: "non-zero", message: "docs/dependencies.md pins pgschema" },
    },
    {
      name: "plan-sql-edited",
      plant: [{ kind: "append", path: "deploy/plan/0001_init.sql", content: "\n-- edited by hand\n" }],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "does not match deploy/plan/CHECKSUMS" },
    },
    {
      // Anchored to the plan itself rather than to a count of its operations: the plant flips the first
      // operation and the witness proves the file no longer matches its digests, so a plan that grows
      // cannot turn this case into a setup failure that proves nothing.
      name: "plan-json-edited",
      plant: [
        {
          kind: "run",
          script:
            "python3 -c \"import pathlib; p = pathlib.Path('deploy/plan/0001_init.json'); t = p.read_text(); p.write_text(t.replace('\\\"operation\\\": \\\"create\\\"', '\\\"operation\\\": \\\"update\\\"', 1))\"",
          verify: "! sha256sum --quiet --check deploy/plan/CHECKSUMS",
        },
      ],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "does not match deploy/plan/CHECKSUMS" },
    },
    {
      name: "checksums-removed",
      plant: [{ kind: "remove", path: "deploy/plan/CHECKSUMS" }],
      command: APPLY_PLAN,
      expect: { status: "non-zero", message: "deploy/plan/CHECKSUMS is missing" },
    },
    {
      name: "plan-file-removed",
      plant: [{ kind: "remove", path: "deploy/plan/0001_init.sql" }],
      expect: { status: "non-zero", message: "deploy/plan/0001_init.sql is missing" },
    },
    {
      name: "source-moved-ahead",
      plant: [
        { kind: "write", path: "deploy/schema/gate_probe.sql", content: "CREATE TABLE gate_probe (id integer);\n" },
        { kind: "append", path: "deploy/schema/main.sql", content: "\\i gate_probe.sql\n" },
      ],
      expect: { status: "non-zero", message: "is not what deploy/schema/main.sql renders" },
    },
    {
      name: "plan-and-digests-forged",
      // A plan and its digests can both be regenerated by hand; only a fresh render catches the drift.
      plant: [
        {
          kind: "run",
          script: "printf '\\n-- forged\\n' >> deploy/plan/0001_init.sql && sha256sum deploy/plan/0001_init.sql deploy/plan/0001_init.json > deploy/plan/CHECKSUMS",
          verify: "sha256sum --quiet --check deploy/plan/CHECKSUMS && grep -q -- '-- forged' deploy/plan/0001_init.sql",
        },
      ],
      expect: { status: "non-zero", message: "is not what deploy/schema/main.sql renders" },
    },
  ],
};

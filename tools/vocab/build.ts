// Rebuilds the tag vocabulary from the raw syllabus evidence and the hand-authored mapping.
//
// content/vocab.json is generated: a source update is a rebuild, never an edit of the output.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const repoRoot = join(import.meta.dir, "..", "..");
const contentDir = join(repoRoot, "content");
const vocabDir = join(contentDir, "vocab");

interface Statement { id: string; group: string; text: string }
interface RawSource { source: string; total: number; groups: { id: string; title: string }[]; statements: Statement[] }
interface MappingNode { id: string; en: string; parent: string | null }
interface Mapping {
  version: number;
  nodes: MappingNode[];
  th_overrides: Record<string, string | null>;
  mapped: Record<string, string>;
  dropped: Record<string, string>;
}
interface Topic { id: string; en: string; th: string }

const readJson = <T>(path: string): T => JSON.parse(readFileSync(path, "utf8")) as T;

const mapping = readJson<Mapping>(join(vocabDir, "mapping.json"));
const topics = readJson<{ topics: Topic[] }>(join(contentDir, "topics.json")).topics;
const sources = ["ioi", "usaco", "posn", "codeforces"].map(
  (name) => readJson<RawSource>(join(vocabDir, "raw", `${name}.json`)),
);

const statements = new Map<string, { source: string; text: string; group: string }>();
for (const source of sources) {
  for (const statement of source.statements) {
    statements.set(statement.id, { source: source.source, text: statement.text, group: statement.group });
  }
}

const topicsById = new Map(topics.map((topic) => [topic.id, topic]));

// A POSN row written in Thai names the concept in Thai; of several, the shortest reads best as a label.
const posnThai = new Map<string, { th: string; statement: string }>();
for (const [id, nodeId] of Object.entries(mapping.mapped)) {
  const statement = statements.get(id);
  if (!statement || statement.source !== "posn" || !/^[\u0e00-\u0e7f]/.test(statement.text)) continue;
  const best = posnThai.get(nodeId);
  if (!best || statement.text.length < best.th.length) posnThai.set(nodeId, { th: statement.text, statement: id });
}

const aliases = new Map<string, { name: string; source: string; section: string }[]>();
for (const [id, nodeId] of Object.entries(mapping.mapped).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
  const statement = statements.get(id);
  if (!statement) throw new Error(`${id}: mapped but not in any raw source`);
  const list = aliases.get(nodeId) ?? [];
  list.push({ name: statement.text, source: statement.source, section: statement.group });
  aliases.set(nodeId, list);
}

const nodes = mapping.nodes
  .map((node) => {
    const topic = topicsById.get(node.id);
    const thai = posnThai.get(node.id);
    const override = node.id in mapping.th_overrides ? mapping.th_overrides[node.id] : undefined;
    const fromOverride = override ? statements.get(override) : undefined;
    if (override && !fromOverride) throw new Error(`th_overrides: ${node.id} names unknown statement ${override}`);
    const th = override === null ? null : fromOverride ? fromOverride.text : topic ? topic.th : thai ? thai.th : null;
    const thSource = override === null
      ? null
      : fromOverride
        ? { source: "posn", statement: override }
        : topic
          ? { source: "topics", topic: node.id }
          : thai
            ? { source: "posn", statement: thai.statement }
            : null;
    const own = (aliases.get(node.id) ?? []).sort(
      (a, b) => (a.source < b.source ? -1 : a.source > b.source ? 1 : a.name < b.name ? -1 : a.name > b.name ? 1 : 0),
    );
    const usedBy = [...new Set(own.map((alias) => alias.source))].sort();
    return { id: node.id, en: node.en, th, th_source: thSource, parent: node.parent, aliases: own, sources: usedBy };
  })
  .sort((a, b) => (a.id < b.id ? -1 : 1));

const vocabulary = {
  version: 1,
  note: "Generated by tools/vocab/build.ts from content/vocab/raw/*.json and content/vocab/mapping.json. Do not edit.",
  nodes,
};
writeFileSync(join(contentDir, "vocab.json"), JSON.stringify(vocabulary, null, 2) + "\n", "utf8");

const untranslated = nodes.filter((node) => node.th === null).map((node) => node.id);
writeFileSync(
  join(vocabDir, "review-untranslated.json"),
  JSON.stringify(
    {
      version: 1,
      note: "Nodes with no Thai name: no source supplied one and inventing one is not allowed.",
      count: untranslated.length,
      ids: untranslated,
    },
    null,
    2,
  ) + "\n",
  "utf8",
);

const aliasCount = nodes.reduce((sum, node) => sum + node.aliases.length, 0);
console.log(
  `vocab built — nodes ${nodes.length} · aliases ${aliasCount} · untranslated ${untranslated.length} · ` +
    sources.map((s) => `${s.source} ${s.total}`).join(" · "),
);
